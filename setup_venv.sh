#!/usr/bin/env bash
# ==============================================================================
# 🏮 Al-Manara AI Dev Hub Pro - تهيئة البيئة الافتراضية المستقلة (Virtual Environment)
# ==============================================================================

set -e

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$SCRIPT_DIR"

echo "=========================================================="
echo "  🏮 تهيئة البيئة الافتراضية (.venv) لـ AI Dev Hub Pro"
echo "=========================================================="

# 1. إنشاء البيئة إذا لم تكن موجودة
if [ ! -d ".venv" ]; then
    echo "[*] إنشاء بيئة افتراضية جديدة باسم .venv ..."
    python3 -m venv .venv
    echo "[✓] تم إنشاء مجلد البيئة بنجاح."
else
    echo "[i] البيئة الافتراضية .venv موجودة مسبقاً."
fi

# 2. تفعيل البيئة
source .venv/bin/activate

# 3. تحديث وتثبيت المتطلبات
echo "[*] تحديث pip وتثبيت متطلبات المشروع..."
pip install --upgrade pip
pip install -r requirements.txt

echo ""
echo "=========================================================="
echo "  ✅ تم إعداد وتفعيل البيئة الافتراضية بنجاح!"
echo "=========================================================="
echo "  📌 للعودة والدخول إلى البيئة في أي جلسة مستقبلية، نفذ فقط:"
echo "     source $SCRIPT_DIR/.venv/bin/activate"
echo ""
echo "  📌 لتشغيل البرنامج مباشرة داخل البيئة:"
echo "     python3 ai_hub.py"
echo ""
echo "  📌 للخروج من البيئة الافتراضية في أي وقت:"
echo "     deactivate"
echo "=========================================================="
